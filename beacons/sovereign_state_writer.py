"""Data-only sovereign_state.py writer.

beacons/sovereign_state_writer.py:write_sovereign_state() writes
`STATE = {...}` (built-in literals only) next to this module, so the
read-only loader (beacons/sovereign_state_loader.py) can parse it with
ast.literal_eval and it is never imported or exec'd.
"""
from __future__ import annotations

import datetime
import math
import os
from typing import Any


def _to_native(obj):
    """Recursively convert numpy scalars/arrays (and other non-literal values)
    to built-in Python types so the written file is ast.literal_eval-safe."""
    try:
        import numpy as np
    except ImportError:
        np = None
    if np is not None:
        if isinstance(obj, np.ndarray):
            return _to_native(obj.tolist())
        if isinstance(obj, np.generic):
            return _to_native(obj.item())
    if isinstance(obj, dict):
        return {str(k) if not isinstance(k, (str, int, float, bool)) else k: _to_native(v)
                for k, v in obj.items()}
    if isinstance(obj, tuple):
        return tuple(_to_native(v) for v in obj)
    if isinstance(obj, (list, set, frozenset)):
        return [_to_native(v) for v in obj]
    if isinstance(obj, float) and not math.isfinite(obj):
        return repr(obj)  # 'inf' / 'nan' are not Python literals
    if isinstance(obj, complex) and not (math.isfinite(obj.real) and math.isfinite(obj.imag)):
        return repr(obj)
    if obj is None or isinstance(obj, (bool, int, float, complex, str, bytes)):
        return obj
    if isinstance(obj, (datetime.datetime, datetime.date)):
        return obj.isoformat()
    return str(obj)


def write_sovereign_state(final_metrics, path=None):
    """Write `STATE = {...}` (built-in literals only) to sovereign_state.py next
    to this module, or to `path`. Returns the path written."""
    import pprint
    if path is None:
        path = os.path.join(os.path.dirname(os.path.abspath(__file__)), "sovereign_state.py")
    state = _to_native(final_metrics)
    with open(path, "w", encoding="utf-8") as f:
        f.write("# -*- coding: utf-8 -*-\n")
        f.write("# Sovereign State – Generated by Consecutive Run (Options 0-24)\n")
        f.write(f"# Timestamp: {state.get('timestamp')}\n\n")
        f.write("STATE = " + pprint.pformat(state, sort_dicts=False, width=100) + "\n")
    return path
