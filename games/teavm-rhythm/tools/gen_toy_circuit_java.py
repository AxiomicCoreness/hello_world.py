#!/usr/bin/env python3
"""Regenerate logic/ToyCircuitXml.java from src/main/webapp/connectomes/toy_lane_circuit.xml.

The browser build can't read files from the classpath, so the toy circuit is
embedded as a string constant. ToyCircuitXmlTest fails if the two drift.
Run from games/teavm-rhythm:  python3 tools/gen_toy_circuit_java.py
"""
import json
import pathlib

root = pathlib.Path(__file__).resolve().parent.parent
xml = (root / "src/main/webapp/connectomes/toy_lane_circuit.xml").read_text(encoding="utf-8")
lines = xml.split("\n")
body = "\n".join("            + " + json.dumps(l + ("\n" if i < len(lines) - 1 else ""), ensure_ascii=True)
                 for i, l in enumerate(lines) if not (i == len(lines) - 1 and l == ""))
src = f'''package com.fruitfly.games.rhythm.logic;

/**
 * GENERATED by tools/gen_toy_circuit_java.py from
 * src/main/webapp/connectomes/toy_lane_circuit.xml. Do not edit by hand.
 *
 * TOY CIRCUIT, not the Drosophila connectome (see the XML comment).
 */
public final class ToyCircuitXml {{
    private ToyCircuitXml() {{
    }}

    public static final String PATH = "connectomes/toy_lane_circuit.xml";

    public static final String XML = ""
{body};
}}
'''
out = root / "src/main/java/com/fruitfly/games/rhythm/logic/ToyCircuitXml.java"
out.write_text(src, encoding="utf-8")
print(f"wrote {out.relative_to(root)} ({len(xml)} chars)")
