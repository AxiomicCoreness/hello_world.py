import com.fruitfly.brain.LIFRK4;
import java.io.IOException;
import java.io.PrintWriter;
import java.lang.reflect.Field;
import java.lang.reflect.Method;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.Paths;

/**
 * Writes golden LIF traces from the REAL root-project LIFRK4
 * (src/main/java/com/fruitfly/brain/LIFRK4.java) for LifRk4ParityTest.
 *
 * Not part of the Maven build: it's compiled by tools/regen-lif-traces.sh
 * together with the root LIFRK4.java, so the game module stays standalone.
 *
 * LIFRK4 only exposes state between ticks, so per-substep states are taken
 * by driving its private substep(double) with reflection, adding each input
 * to its private g exactly as stepTick(double[]) and stepTick(double) do.
 * Every tick is then cross-checked bit for bit against a second instance
 * driven only through the public stepTick API, so the reflection path
 * can't drift from the real one. A spike is a substep after which
 * refractoryRemaining() == REFRAC, since only a spike sets it to REFRAC.
 *
 * Usage: java LifGoldenTraceGen <out-file> <source-label>
 */
public final class LifGoldenTraceGen {
    private static final int TICKS = 4;

    private static Field gField;
    private static Method substep;

    public static void main(String[] args) throws Exception {
        if (args.length != 2) {
            throw new IllegalArgumentException("usage: LifGoldenTraceGen <out-file> <source-label>");
        }
        gField = LIFRK4.class.getDeclaredField("g");
        gField.setAccessible(true);
        substep = LIFRK4.class.getDeclaredMethod("substep", double.class);
        substep.setAccessible(true);

        Path out = Paths.get(args[0]);
        Files.createDirectories(out.toAbsolutePath().getParent());
        try (PrintWriter w = new PrintWriter(Files.newBufferedWriter(out, StandardCharsets.UTF_8))) {
            w.println("# Golden LIF traces from the real com.fruitfly.brain.LIFRK4.");
            w.println("# Generated by tools/LifGoldenTraceGen.java. Do not hand-edit; see README.");
            w.println("source " + args[1]);
            w.println("const V_REST " + hex(LIFRK4.V_REST));
            w.println("const V_THRESH " + hex(LIFRK4.V_THRESH));
            w.println("const V_RESET " + hex(LIFRK4.V_RESET));
            w.println("const TAU_V " + hex(LIFRK4.TAU_V));
            w.println("const TAU_G " + hex(LIFRK4.TAU_G));
            w.println("const REFRAC " + hex(LIFRK4.REFRAC));
            w.println("const SYNAPTIC_GAIN " + hex(LIFRK4.SYNAPTIC_GAIN));
            w.println("const BRAIN_TICK_MS " + hex(LIFRK4.BRAIN_TICK_MS));
            w.println("const SUBSTEPS " + LIFRK4.SUBSTEPS);

            int n = LIFRK4.SUBSTEPS;
            // 1. one suprathreshold pulse at substep 0
            double[][] a = new double[TICKS][n];
            a[0][0] = 60.0;
            perSubstep(w, "pulse60", a);
            // 2. subthreshold pulse
            double[][] b = new double[TICKS][n];
            b[0][0] = 40.0;
            perSubstep(w, "pulse40_subthreshold", b);
            // 3. huge pulse mid-tick: repeated spikes, refractory clamp and rounding
            double[][] c = new double[TICKS][n];
            c[0][17] = 500.0;
            perSubstep(w, "pulse500_mid_tick", c);
            // 4. pulse in the last substep, so it carries across the tick boundary
            double[][] d = new double[TICKS][n];
            d[0][n - 1] = 75.0;
            perSubstep(w, "pulse75_last_substep", d);
            // 5. dense deterministic pseudo-random drive (inputs are written to the file)
            double[][] e = new double[TICKS][n];
            long s = 2026L;
            for (int t = 0; t < TICKS; t++) {
                for (int i = 0; i < n; i++) {
                    s = s * 6364136223846793005L + 1442695040888963407L;
                    int r = (int) (s >>> 40);
                    e[t][i] = (r % 7 == 0) ? (r % 4000) / 100.0 : 0.0;
                }
            }
            perSubstep(w, "lcg_dense_2026", e);
            // 6. legacy stepTick(double): input lands after each tick
            legacy(w, "legacy_ticks", new double[] {60.0, 0.0, 45.0, 300.0});
        }
    }

    private static void perSubstep(PrintWriter w, String name, double[][] in) throws Exception {
        LIFRK4 viaSubstep = new LIFRK4();
        LIFRK4 viaPublic = new LIFRK4();
        w.println("trace " + name + " persubstep " + in.length);
        for (int t = 0; t < in.length; t++) {
            StringBuilder sb = new StringBuilder("in ").append(t);
            for (double x : in[t]) {
                sb.append(' ').append(hex(x));
            }
            w.println(sb);
            for (int i = 0; i < LIFRK4.SUBSTEPS; i++) {
                gField.setDouble(viaSubstep, gField.getDouble(viaSubstep) + in[t][i]);
                substep.invoke(viaSubstep, LIFRK4.BRAIN_TICK_MS / LIFRK4.SUBSTEPS);
                state(w, t, i, viaSubstep);
            }
            viaPublic.stepTick(in[t]);
            crossCheck(name, t, viaSubstep, viaPublic);
        }
        w.println("end " + name);
    }

    private static void legacy(PrintWriter w, String name, double[] deltas) throws Exception {
        LIFRK4 viaSubstep = new LIFRK4();
        LIFRK4 viaPublic = new LIFRK4();
        w.println("trace " + name + " legacy " + deltas.length);
        for (int t = 0; t < deltas.length; t++) {
            w.println("delta " + t + " " + hex(deltas[t]));
            for (int i = 0; i < LIFRK4.SUBSTEPS; i++) {
                substep.invoke(viaSubstep, LIFRK4.BRAIN_TICK_MS / LIFRK4.SUBSTEPS);
                state(w, t, i, viaSubstep);
            }
            gField.setDouble(viaSubstep, gField.getDouble(viaSubstep) + deltas[t]);
            viaPublic.stepTick(deltas[t]);
            crossCheck(name, t, viaSubstep, viaPublic);
            w.println("after " + t + " " + hex(viaSubstep.v()) + " " + hex(viaSubstep.g()) + " "
                    + hex(viaSubstep.refractoryRemaining()));
        }
        w.println("end " + name);
    }

    private static void state(PrintWriter w, int t, int i, LIFRK4 n) {
        boolean spike = n.refractoryRemaining() == LIFRK4.REFRAC;
        w.println("s " + t + " " + i + " " + hex(n.v()) + " " + hex(n.g()) + " "
                + hex(n.refractoryRemaining()) + " " + (spike ? 1 : 0));
    }

    private static void crossCheck(String name, int t, LIFRK4 a, LIFRK4 b) {
        if (Double.doubleToRawLongBits(a.v()) != Double.doubleToRawLongBits(b.v())
                || Double.doubleToRawLongBits(a.g()) != Double.doubleToRawLongBits(b.g())
                || Double.doubleToRawLongBits(a.refractoryRemaining())
                        != Double.doubleToRawLongBits(b.refractoryRemaining())) {
            throw new IllegalStateException("substep path diverged from public stepTick in "
                    + name + " tick " + t);
        }
    }

    /** Exact, round-trippable text form (Double.parseDouble reads it back). */
    private static String hex(double x) {
        return Double.toHexString(x);
    }

    private LifGoldenTraceGen() {
    }
}
